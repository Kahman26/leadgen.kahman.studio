DEFAULT = "booking"


def get(code):
    return RULES.get(code or DEFAULT) or RULES[DEFAULT]


def collectable():
    """Коды ниш, для которых есть правила сбора — в порядке справочника."""
    return list(RULES)


def code_of(niche_id):
    """Код ниши по её номеру. У заведённых вручную кода нет — None."""
    if not niche_id:
        return None
    r = db.conn().execute("SELECT code FROM niches WHERE id=?", (niche_id,)).fetchone()
    return r["code"] if r else None


def niche_id_of(code):
    r = db.conn().execute("SELECT id FROM niches WHERE code=?", (code,)).fetchone()
    return r["id"] if r else None


def title_of(niche_id):
    r = db.conn().execute("SELECT title FROM niches WHERE id=?", (niche_id,)).fetchone()
    return r["title"] if r else ""


def okved_for(niche_id):
    """ОКВЭД для сверки с ЕГРЮЛ. Ниша без правил — без проверки ОКВЭД,
    чтобы не занижать уверенность из-за чужих кодов."""
    code = code_of(niche_id)
    if niche_id and code not in RULES:
        return ()
    return get(code)["okved"]


def checks_booking(niche_id):
    """Проверять ли систему брони. Лид без ниши — по старой логике, как
    бронирование: так было до появления ниш."""
    if not niche_id:
        return True
    return get(code_of(niche_id))["booking"] if code_of(niche_id) in RULES else False


def category_for(code, tags, name):
    """Категория объекта OSM: подсказка по названию важнее тега.

    Возвращает (категория или None, подходит ли объект нише вообще).
    """
    rules = get(code)
    low = (name or "").lower().replace("ё", "е")
    if not rules.get("chains") and (tags.get("brand:wikidata") or tags.get("brand:wikipedia")):
        return None, False
    if rules.get("exclude") and re.search(rules["exclude"], low):
        return None, False
    for pattern, title in rules["hints"]:
        if re.search(pattern.replace("ё", "е"), low):
            return title, True
    for key, values in rules["osm"].items():
        v = tags.get(key)
        if v in values:
            title = values[v]
            return title, title is not None
    return None, False
