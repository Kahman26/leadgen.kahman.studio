def main():
    ok = bad = 0
    for category, name, url, city, note, strengths in REFERENCES:
        try:
            ref = refs.save(category, name, url, city=city, note=note,
                            strengths=strengths)
            state = ref["site_status"]
            mark = "OK" if state == "ok" else "!!"
            print(f"{mark} {category:20} {name:28} {state} "
                  f"бронь:{ref['booking_type'] or '-'}")
            ok += state == "ok"
            bad += state != "ok"
        except Exception as exc:
            bad += 1
            print(f"!! {category:20} {name:28} ошибка: {exc}")

    print(f"\nГотово: {ok} проверено успешно, {bad} с замечаниями")


