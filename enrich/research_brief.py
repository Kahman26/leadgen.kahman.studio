# -*- coding: utf-8 -*-
"""Автопроверка объекта вручную, через чат с Claude.

Обращений к API здесь нет. Сервис только готовит запрос с данными лида
и разбирает JSON, который человек принесёт обратно из чата.

Порядок работы:
1. В карточке нажать «Запрос для чата» — текст с данными объекта копируется.
2. Вставить его в чат с Claude, у которого есть поиск в интернете.
3. Вернуть полученный JSON в карточку кнопкой «Вставить результат».

Правило про выдумки остаётся в самом запросе: модель должна писать только
то, что видела в выдаче, и давать ссылку на каждый факт. Выдуманный телефон
хуже пустого поля — по нему позвонят.
"""

import json
import re

BRIEF = """Ты помогаешь агентству веб-разработки разобраться в потенциальном клиенте.
Это объект размещения или отдыха в городе {city}: отель, база отдыха, баня,
глэмпинг или посуточные квартиры.

Найди в интернете и проверь:
1. Работает ли бизнес сейчас или закрылся.
2. Какой у него ДЕЙСТВУЮЩИЙ сайт. Старый адрес мог перестать открываться,
   компания могла переехать на новый домен.
3. Через какие площадки-посредники он принимает брони: Суточно.ру, Островок,
   Авито, Яндекс.Путешествия, 101 отель, 2ГИС, YClients и подобные.
4. Контакты руководителя или владельца, если они есть в открытых источниках.
5. Какие у бизнеса проблемы с онлайн-присутствием: нет сайта, сайт не
   открывается, устарел, нет мобильной версии, нет онлайн-бронирования,
   брони идут только через агрегаторы с комиссией.
6. Реквизиты компании: юридическое название, ИНН, ОГРН, юридический и
   фактический адрес.

Про сайт учти два случая, которые легко принять за рабочий сайт:
- домен отвечает, но ведёт на парковку, объявление о продаже или редиректом
  на агрегатор — это то же самое, что сайта нет;
- своего домена нет, но есть страница-визитка на чужом конструкторе
  (2gis.biz, clients.site, navse360.ru, orgs.biz и подобные). Её тоже
  записывай в website, пометив в problems, что это чужой поддомен.

ЖЁСТКИЕ ПРАВИЛА:
- Пиши только то, что реально видел в результатах поиска. Ничего не достраивай
  по смыслу и не угадывай по названию.
- На каждый факт должна быть ссылка, откуда он взят.
- Не нашёл — ставь null или пустой список. Это нормальный ответ.
- Телефон и почту бери со страниц самого бизнеса или его карточек на площадках.
- Соцсети компании — это не личные контакты руководителя.

ЧТО УЖЕ ИЗВЕСТНО:
{known}

Ответ — ОДИН объект JSON без пояснений вокруг, по схеме:
{{
  "is_open": true | false | null,
  "status_note": "коротко, что известно о работе бизнеса",
  "website": "https://... или null",
  "website_source": "ссылка, где увидел этот адрес",
  "aggregators": [{{"name": "Суточно.ру", "url": "https://..."}}],
  "director": {{"name": "ФИО или null", "post": "должность или null",
               "source": "ссылка"}},
  "company": {{"legal_name": "ООО «...» или null", "inn": "10 цифр или null",
               "ogrn": "13 цифр или null", "legal_address": "юр. адрес или null",
               "address": "фактический адрес объекта или null",
               "phones": ["+7...", "..."], "source": "ссылка"}},
  "contacts": {{"phone": "+7... или null", "telegram": "ник или null",
               "vk": "адрес или null", "email": "почта или null",
               "source": "ссылка"}},
  "problems": ["проблема с онлайн-присутствием", "..."],
  "summary": "2-4 предложения о бизнесе и его ситуации",
  "sources": ["все использованные ссылки"]
}}"""

KNOWN_FIELDS = (
    ("Название", "name"),
    ("Категория", "category"),
    ("Адрес", "address"),
    ("Известный сайт", "website"),
    ("Телефон", "phone"),
    ("В реестре", "org_name"),
    ("ИНН", "inn"),
    ("Юр. адрес", "legal_address"),
)

SITE_STATE = {
    "dead": "известный сайт не открывается — возможно, сменили домен",
    "parked": "домен отвечает, но сайта компании на нём нет — парковка "
              "или переадресация; нужен настоящий адрес",
    "none": "сайт неизвестен",
    "blocked": "сайт закрыт защитой, проверить автоматически не удалось",
    "ok": "известный сайт работает",
}


def build(lead, city="Екатеринбург"):
    """Собирает текст запроса для чата по данным лида."""
    known = [f"{label}: {lead[key]}" for label, key in KNOWN_FIELDS if lead.get(key)]

    state = SITE_STATE.get(lead.get("site_status"))
    if state:
        known.append(f"Состояние сайта по нашей проверке: {state}")

    return BRIEF.format(city=city, known="\n".join(known) or "только название")


def parse(text):
    """Достаёт объект JSON из того, что вставил человек.

    Терпим к обёртке: ответ мог прийти в блоке ```json или с текстом вокруг.
    """
    text = (text or "").strip()
    if not text:
        return None, "Пусто — вставьте ответ из чата"

    fence = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.S)
    if fence:
        text = fence.group(1)
    else:
        start, end = text.find("{"), text.rfind("}")
        if start == -1 or end <= start:
            return None, "В тексте нет объекта JSON"
        text = text[start:end + 1]

    try:
        data = json.loads(text)
    except ValueError as exc:
        return None, f"JSON не разбирается: {exc}"

    if not isinstance(data, dict):
        return None, "Ожидался объект JSON, а не список"
    return data, ""
